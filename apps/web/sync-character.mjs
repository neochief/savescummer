// Keep the static website release self-contained while sharing the desktop artwork and eye rig.
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const svg = new URL('../ui/public/character/popup-hug.svg', import.meta.url);
const eyes = new URL('../ui/src/skeletonEyes.ts', import.meta.url);
const outputs = [
  ['popup-hug.svg', readFileSync(svg, 'utf8')],
  ['skeleton-eyes.js', '// Generated by apps/web/sync-character.mjs from apps/ui/src/skeletonEyes.ts.\n'
    + stripTypeScriptTypes(readFileSync(eyes, 'utf8'))],
];
for (const [name, content] of outputs) {
  const target = new URL(`public/character/${name}`, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Run node apps/web/sync-character.mjs: public/character/${name} is out of date`);
  } else writeFileSync(target, content);
}
